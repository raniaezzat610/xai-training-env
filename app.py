# منطقة رفع ملف الوورد
st.subheader("📄 رفع مسودة النشاط التعليمي (ملف Word)")
uploaded_file = st.file_uploader(
    "قم برفع ملف خطة الدرس أو النشاط بصيغة (.docx) للتحليل التلقائي:",
    type=["docx"],
)

