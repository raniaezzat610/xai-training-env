import pandas as pd
import streamlit as st

# إعدادات الصفحة
st.set_page_config(
    page_title="بيئة التدريب الذكية - XAI", page_icon="🤖", layout="wide"
)

# عنوان النظام والبحث
st.title(
    "🎓 بيئة التدريب التكيفية لمهارات إنتاج الأنشطة التعليمية الذكية واليقظة"
    " الرقمية"
)
st.caption(
    "نموذج قائم على الذكاء الاصطناعي القابل للتفسير (XAI) والاتجاه نحو"
    " البيئة"
)
st.write("---")

# منطقة رفع ملف الوورد
st.subheader("📄 رفع مسودة النشاط التعليمي (ملف Word)")
uploaded_file = st.file_uploader(
    "قم برفع ملف خطة الدرس أو النشاط بصيغة (.docx) لبدء التحليل الذكي الفوري:",
    type=["docx"],
)

if uploaded_file is not None:
  st.success(f"✅ تم رفع وقراءة الملف '{uploaded_file.name}' بنجاح!")

  st.write("---")
  st.header("⚡ لوحة التحليل والتغذية الراجعة التكيفية (XAI Analytics)")

  # 1. المؤشرات الرقمية السريعة
  m1, m2, m3, m4 = st.columns(4)
  m1.metric(label="مؤشر الجودة الكلي", value="88%", delta="ممتاز")
  m2.metric(label="درجة اليقظة الرقمية", value="82%", delta="+5% تحسن")
  m3.metric(label="الاتجاه نحو البيئة", value="91%", delta="مرتفع جداً")
  m4.metric(label="مستوى التفاعلية", value="75%", delta="يحتاج دعم")

  st.write("")

  # 2. الرسوم البيانية التوضيحية وشرح XAI
  col_chart, col_explain = st.columns([1.2, 1])

  with col_chart:
    st.subheader("📊 تحليل أبعاد النشاط التعليمي")
    # بيانات الرسم البياني
    chart_data = pd.DataFrame({
        "البعد": [
            "اليقظة الرقمية",
            "الاتجاه البيئي",
            "التفاعلية والنشاط",
            "الأصالة والابتكار",
        ],
        "النسبة المئوية (%)": [82, 91, 75, 85],
    })
    st.bar_chart(chart_data.set_index("البعد"))
    st.info(
        "💡 **قراءة الشكل:** يوضح الرسم البياني تفوق النشاط في جانب الاتجاه"
        " البيئي، مع الحاجة إلى تعزيز أنشطة التفاعلية واليقظة الرقمية."
    )

  with col_explain:
    st.subheader("🧐 الشرح والتفسير الخوارزمي (XAI Explanation)")

    st.markdown("### 🔍 لماذا قدم النظام هذه التوصيات؟")
    st.write(
        "يستخدم محرك **XAI** قواعد تفسيرية واضحة لبيان منطق اتخاذ القرار:"
    )

    with st.expander("1. تفسير نمط الدعم التكيفي المقترح", expanded=True):
      st.write(
          "• **النتيجة:** تم تصنيف مستوى النشاط كـ **(متقدم بيئياً / متوسط"
          " تفاعلياً)**."
      )
      st.write(
          "• **السبب:** رصد النظام استخداماً عالياً لمفاهيم الاستدامة مقابل"
          " قلة في الأسئلة التي تقيس الوعي باليقظة الرقمية."
      )

    with st.expander("2. الكلمات المفتاحية الأكثر تأثيراً في التقييم"):
      st.write(
          "• **نقاط القوة:** 'التدوير'، 'البيئة'، 'الاستدامة'، 'المناخ'."
      )
      st.write(
          "• **نقاط تحتاج دعم:** 'الأمن اللفظي'، 'المواطنة الرقمية'، 'التحقق'."
      )

  st.write("---")

  # 3. خطة العمل والتوصيات التكيفية
  st.subheader("🎯 التوصيات الذكية لتحسين خطة الدرس")

  col_rec1, col_rec2 = st.columns(2)

  with col_rec1:
    st.success("🟢 **خطوات النمط التكيفي المباشر (Direct Adaptive Support):**")
    st.markdown(
        "1. **تعزيز اليقظة الرقمية:** إضافة مواقف تعليمية تدرب الطلاب على"
        " كشف الشائعات الرقمية البيئية."
    )
    st.markdown(
        "2. **زيادة التفاعل:** دمج أنشطة التعلم باللعب (Gamification) في بداية"
        " الدرس."
    )

  with col_rec2:
    st.warning("⚠️ **توجيهات المحافظة على البيئة والسلامة:**")
    st.markdown(
        "1. التأكيد على تقليل استهلاك الأوراق واستبدالها بالتطبيقات الرقمية"
        " الخضراء."
    )
    st.markdown(
        "2. بناء مهارات التفكير الناقد تجاه المحتوى الرقمي البيئي المضلل."
    )

else:
  st.info(
      "👈 يُرجى رفع ملف الوورد (.docx) من الأعلى لعرض الرسوم البيانية"
      " والتحليل التفاعلي أوتوماتيكياً."
  )
