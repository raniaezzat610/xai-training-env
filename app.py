import streamlit as st

# إعدادات الصفحة
st.set_page_title_config = st.set_page_config(
    page_title="بيئة التدريب الذكية - XAI", page_icon="🤖", layout="wide"
)

st.title(
    "🎓 بيئة التدريب لمهارات إنتاج الأنشطة التعليمية الذكية واليقظة الرقمية"
)
st.markdown(
    "**العنوان:** فاعلية أنماط الدعم التكيفية في بيئة تدريب قائمة على الذكاء الاصطناعي القابل للتفسير (XAI)"
)
st.write("---")

# القائمة الجانبية للتنقل بين المراحل
st.sidebar.header("مراحل بيئة التدريب")
scene = st.sidebar.radio(
    "اختر المشهد:",
    [
        "1. الأهداف التكيفية",
        "2. مسودة المعلم ورفع ملف الوورد",
        "3. محرك الذكاء التفسيري (XAI)",
        "4. تقرير الأداء الشامل",
    ],
)

if scene == "1. الأهداف التكيفية":
  st.subheader("المشهد الأول: تحديد التوجيه التربوي والأهداف الذكية")
  st.info('توصية المعلمة "سارة": بحاجة لتنمية مهارة التفاعلية واليقظة الرقمية.')
  st.write(
      "في هذا المشهد يتم تحليل الملف الشخصي للمعلم ومستواه الأكاديمي لتكييف"
      " الأهداف الفردية."
  )

elif scene == "2. مسودة المعلم ورفع ملف الوورد":
  st.subheader("المشهد الثاني: إدخال مسودة المعلم ورفع ملفات الورد (Word)")
  st.write("يمكنكِ هنا رفع ملف خطة الدرس أو النشاط (Word Document):")

  uploaded_file = st.file_uploader(
      "اختر ملف الوورد (.docx)", type=["docx", "doc", "txt"]
  )

  activity_name = st.text_input(
      "اسم النشاط:", "قصة الأرقام التفاعلية لخدمة الاستدامة البيئية"
  )
  activity_desc = st.text_area(
      "الوصف:", "تصميم نشاط تفاعلي يعلم الأطفال الأرقام بالاستناد إلى قصة."
  )

  if uploaded_file is not None:
    st.success(f"تم رفع الملف '{uploaded_file.name}' بنجاح!")
    st.info(
        "جاري تحليل محتوى الملف عبر محرك الذكاء الاصطناعي لتكييفه مع معايير"
        " اليقظة الرقمية والبيئة..."
    )

elif scene == "3. محرك الذكاء التفسيري (XAI)":
  st.subheader("المشهد الثالث: التغذية الراجعة التفسيرية المكشوفة (XAI Engine)")
  st.warning("لماذا تم هذا التقييم؟")
  st.markdown(
      "- **المعيار:** التفاعلية، اليقظة الرقمية، والاتجاه نحو البيئة."
  )
  st.markdown(
      "- **التحليل الخوارزمي:** النشاط الحالي يفتقر إلى سيناريوهات متعددة"
      " لتعزيز التفاعل المستدام."
  )

  st.error(
      "💡 **التفسير المفسر للتطور التكيفي:** يجب إضافة خيارات رد تفاعلية مدعومة"
      " باليقظة الرقمية لتجنب تشوهات المعرفة البيئية لدى الطلاب."
  )

elif scene == "4. تقرير الأداء الشامل":
  st.subheader("المشهد الرابع: تقرير أداء شامل وذكي (Smart Comprehensive Report)")
  st.success("🎉 تم حفظ النشاط بنجاح وتحقيق معايير بيئة التدريب!")
  st.metric(label="مؤشر الثقة التكيفي (Confidence Score)", value="590 / 800")

  st.write("### ملخص المخرجات التعليمية:")
  st.markdown(
      "1. توعية بيئة التعلم بأهمية الأمن اللفظي واللغة العربية المستدامة."
  )
  st.markdown("2. المعيار التكيفي الدعم لتنمية التفكير للطلاب العرب.")
  st.markdown("3. التحليل الخوارزمي: تنمية اليقظة الرقمية لتلافي تشوهات المعرفة.")
  st.markdown("4. الاتجاه نحو البيئة: دعم تفعيل الحصص لخدمة الأصول البيئية الذكية.")